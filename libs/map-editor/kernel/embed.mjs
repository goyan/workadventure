// Writes the kernel built by build.sh as a TypeScript module: its bytes in base64, and the fingerprint of the
// source they were built from (tests/WaterKernelWasm.test.ts checks it against water_kernel.c).
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const [source, wasm, out] = process.argv.slice(2);
const bytes = readFileSync(wasm);
const sha = createHash("sha256").update(readFileSync(source)).digest("hex");
const base64 = bytes.toString("base64");
const lines = base64.match(/.{1,100}/g) ?? [];
writeFileSync(
    out,
    `// Generated by libs/map-editor/kernel/build.sh from kernel/water_kernel.c: do not edit.
/** The fingerprint (SHA-256) of the water_kernel.c these bytes were built from. */
export const WATER_KERNEL_SOURCE_SHA256 = "${sha}";
/** The kernel of the water, compiled to WebAssembly (${bytes.length} bytes), in base64. */
// prettier-ignore
export const WATER_KERNEL_WASM_BASE64 =
${lines.map((line) => `    "${line}"`).join(" +\n")};
`,
);
console.log(`wrote ${out}: ${bytes.length} bytes of WebAssembly, source ${sha.slice(0, 12)}`);
