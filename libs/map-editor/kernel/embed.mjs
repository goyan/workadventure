// Writes the kernel built by build.sh as a TypeScript module: its bytes in base64 (for a memory of its own, and for
// a memory threads share), and the fingerprint of the source they were built from (tests/WaterKernelWasm.test.ts
// checks it against water_kernel.c).
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const [source, wasm, shared, out] = process.argv.slice(2);
const sha = createHash("sha256").update(readFileSync(source)).digest("hex");
/**
 * The kernel keeps nothing of its own in the memory: no data, and no global but the pointer of its stack, which
 * each thread sets on a stack of its own (WaterKernelWasm). Several threads run it on one memory: a datum of the
 * module there would be shared by all of them without their knowing. Checked on the bytes built.
 */
const checkStateless = (file, bytes) => {
    const sections = [];
    let at = 8;
    const leb = () => {
        let value = 0;
        let shift = 0;
        for (;;) {
            const byte = bytes[at++];
            value |= (byte & 127) << shift;
            if (byte < 128) return value >>> 0;
            shift += 7;
        }
    };
    let globals = 0;
    while (at < bytes.length) {
        const id = bytes[at++];
        const size = leb();
        if (id === 6) {
            const from = at;
            globals = leb();
            at = from;
        }
        sections.push(id);
        at += size;
    }
    if (sections.includes(11) || sections.includes(12)) throw new Error(`${file}: the kernel has data in the memory`);
    // The pointer of the stack, and where the heap starts (a constant).
    if (globals > 2) throw new Error(`${file}: the kernel has ${globals} globals, two are expected`);
};
const constant = (name, file, what) => {
    const bytes = readFileSync(file);
    checkStateless(file, bytes);
    const lines = bytes.toString("base64").match(/.{1,100}/g) ?? [];
    return `/** The kernel of the water, compiled to WebAssembly ${what} (${bytes.length} bytes), in base64. */
// prettier-ignore
export const ${name} =
${lines.map((line) => `    "${line}"`).join(" +\n")};
`;
};
writeFileSync(
    out,
    `// Generated by libs/map-editor/kernel/build.sh from kernel/water_kernel.c: do not edit.
/** The fingerprint (SHA-256) of the water_kernel.c these bytes were built from. */
export const WATER_KERNEL_SOURCE_SHA256 = "${sha}";
${constant("WATER_KERNEL_WASM_BASE64", wasm, "for a memory of its own")}${constant("WATER_KERNEL_SHARED_WASM_BASE64", shared, "for a memory threads share")}`,
);
console.log(`wrote ${out}: source ${sha.slice(0, 12)}`);
